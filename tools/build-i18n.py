#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate i18n/bundle.js from the JSON translation files.

Why this exists
---------------
Browsers block fetch() on file:// URLs, so opening index.html by double-clicking
leaves js/i18n.js unable to read i18n/*.json — the page freezes on its inline
English fallback and neither language button responds.

bundle.js is a plain <script> (no fetch involved), so it works from disk. Over
HTTP the JSON files are still fetched and remain authoritative; the bundle is
only used when the page is opened from the filesystem, or if a fetch fails.

Usage
-----
    python tools/build-i18n.py

Run it after editing i18n/en.json or i18n/tr.json — otherwise the file://
preview keeps showing the previous copy. Over HTTP nothing goes stale.
"""
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I18N = os.path.join(ROOT, "i18n")
OUT = os.path.join(I18N, "bundle.js")

langs = sorted(f[:-5] for f in os.listdir(I18N) if f.endswith(".json"))
if not langs:
    sys.exit("no .json files found in i18n/")

data = {}
for lang in langs:
    path = os.path.join(I18N, lang + ".json")
    try:
        data[lang] = json.loads(io.open(path, encoding="utf-8").read())
    except ValueError as exc:
        sys.exit("%s.json is not valid JSON: %s" % (lang, exc))

body = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=False)
out = (
    "/* AUTO-GENERATED by tools/build-i18n.py — do not edit by hand.\n"
    "   Source of truth: i18n/*.json. Regenerate after changing them:\n"
    "       python tools/build-i18n.py\n"
    "   Exists so the site works when opened directly from disk (file://),\n"
    "   where browsers refuse to fetch() the JSON files. */\n"
    "window.I18N_BUNDLE = " + body + ";\n"
)
io.open(OUT, "w", encoding="utf-8").write(out)

size = os.path.getsize(OUT) / 1024.0
print("i18n/bundle.js written: %s (%.1f KB)" % (", ".join(langs), size))
