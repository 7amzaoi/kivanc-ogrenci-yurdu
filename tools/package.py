# -*- coding: utf-8 -*-
"""Build the zip to upload to Hostinger's public_html/.

    python tools/package.py

Ships only what the browser asks for. The generators, the README and the git
history stay in the repository -- there is no reason for the server to hold
the Python that built the pages.

Refuses to build if the site still has no origin configured, because a site
uploaded without a canonical and without an absolute og:image is a site you
will have to upload again.
"""
import hashlib
import io
import json
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

OUT = "kivanc-site.zip"

# Files at the root that belong on the server.
ROOT_FILES = ["index.html", "rooms.html", "404.html", ".htaccess",
              "robots.txt", "sitemap.xml"]
# Whole directories that belong on the server.
DIRS = ["css", "js", "i18n", "assets"]
# Never ship these, wherever they turn up.
SKIP_EXT = {".py", ".md", ".bak", ".psd", ".zip"}
SKIP_NAME = {"site.config.json", ".DS_Store", "Thumbs.db", ".gitignore"}


def origin():
    try:
        return (json.load(io.open("site.config.json", encoding="utf-8"))
                .get("origin") or "").rstrip("/")
    except (IOError, ValueError):
        return ""


def flatten_css():
    """Concatenate the @import chain into one stylesheet.

    CSS blocks rendering, and the browser cannot even discover the partials
    until main.css has been fetched and parsed -- so the imports cost a whole
    extra round-trip before anything paints. None of the partials contain a
    url() or a nested @import, so plain concatenation in import order is
    exactly equivalent.
    """
    src = io.open("css/main.css", encoding="utf-8").read()
    names = re.findall(r'@import\s+url\(["\']([^"\']+)["\']\)', src)
    if not names:
        raise SystemExit("css/main.css: no @import found -- has it already been flattened?")

    out = ["/* Kıvanç Kız Yurdu — generated by tools/package.py.\n"
           "   Edit the partials in css/, not this file. */\n"]
    for n in names:
        path = os.path.join("css", n)
        if not os.path.exists(path):
            raise SystemExit("css/main.css imports %s, which does not exist" % n)
        out.append("\n/* ===== %s ===== */\n" % n)
        out.append(io.open(path, encoding="utf-8").read())
    return "".join(out), names


def version_token(css):
    """Short content hash covering everything cached long-term."""
    h = hashlib.sha1()
    h.update(css.encode("utf-8"))
    for f in ("js/i18n.js", "js/main.js", "i18n/bundle.js",
              "i18n/en.json", "i18n/tr.json"):
        h.update(io.open(f, "rb").read())
    return h.hexdigest()[:10]


def stamp_versions(html, token):
    """Point the HTML at versioned asset URLs.

    Assets are served with a year of immutable cache, which is right for
    speed and wrong for the next edit: without this, a corrected price or a
    restyled section would keep serving the old file to returning visitors
    and to Hostinger's CDN. The HTML itself is no-cache, so a new token
    reaches everyone on their next page load.
    """
    for path in ("css/main.css", "js/i18n.js", "js/main.js", "i18n/bundle.js"):
        for attr in ("href", "src"):
            html = html.replace('%s="%s"' % (attr, path),
                                '%s="%s?v=%s"' % (attr, path, token))

    # i18n.js reads this when it fetches en.json / tr.json at runtime
    marker = '<script src="i18n/bundle.js?v=%s"></script>' % token
    if marker not in html:
        raise SystemExit("bundle.js script tag not found -- cannot stamp __ASSET_V")
    return html.replace(
        marker,
        '<script>window.__ASSET_V="%s";</script>\n  %s' % (token, marker))


def collect():
    for f in ROOT_FILES:
        if os.path.exists(f):
            yield f
        elif f in ("robots.txt", "sitemap.xml"):
            pass                      # only exist once an origin is set
        else:
            raise SystemExit("missing required file: %s" % f)

    for d in DIRS:
        for base, _dirs, files in os.walk(d):
            if ".git" in base:
                continue
            for name in sorted(files):
                if name in SKIP_NAME:
                    continue
                if os.path.splitext(name)[1].lower() in SKIP_EXT:
                    continue
                # the partials are folded into main.css below
                if base.replace("\\", "/") == "css" and name.startswith("_"):
                    continue
                if base.replace("\\", "/") == "css" and name == "main.css":
                    continue
                yield os.path.join(base, name).replace("\\", "/")


def main():
    o = origin()
    if not o:
        raise SystemExit(
            "site.config.json has no origin.\n"
            "Run  python tools/set-domain.py https://your-domain  first, so the\n"
            "canonical links, og:image, robots.txt and sitemap.xml are stamped\n"
            "before the files are packaged.")

    files = sorted(set(collect()))
    css, partials = flatten_css()
    token = version_token(css)

    if os.path.exists(OUT):
        os.remove(OUT)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            if f.endswith(".html"):
                html = stamp_versions(io.open(f, encoding="utf-8").read(), token) \
                       if f != "404.html" else io.open(f, encoding="utf-8").read()
                z.writestr(f, html.encode("utf-8"))
            else:
                z.write(f, f)
        z.writestr("css/main.css", css.encode("utf-8"))

    total = sum(os.path.getsize(f) for f in files) + len(css.encode("utf-8"))
    print("%s  --  %d files, %.2f MB raw, %.2f MB zipped"
          % (OUT, len(files) + 1, total / 1048576.0,
             os.path.getsize(OUT) / 1048576.0))
    print("css: %d partials flattened into one main.css (%d KB), "
          "saving %d requests and a round-trip"
          % (len(partials), len(css) // 1024, len(partials)))
    print("cache: assets stamped ?v=%s -- edit anything and the URLs change" % token)
    print("origin: %s" % o)
    print()
    print("Upload it in hPanel -> File Manager -> public_html, then use the")
    print("Extract action. Make sure hidden files are shown so .htaccess lands too.")


if __name__ == "__main__":
    main()
