# -*- coding: utf-8 -*-
"""Generate everything that depends on the site's public URL.

Run it after setting "origin" in site.config.json:

    python tools/set-domain.py https://kivancyurdu.com

Everything it writes is derived from i18n/en.json, so the address, phone,
coordinates and prices in the structured data can never drift away from the
address, phone, coordinates and prices the page actually shows.

With no origin configured it still writes the structured data and the
locale tags, and simply leaves out the absolute URLs -- a wrong canonical
is worse than no canonical, so it never guesses one.
"""
import io
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

START = "<!-- seo:start -- generated by tools/build-seo.py; do not hand-edit -->"
END = "<!-- seo:end -->"

OG_IMAGE = "assets/images/og-card.jpg"
PAGES = {"index.html": "", "rooms.html": "rooms.html"}

# Single source of truth for the landing-page slugs: the sitemap below and
# tools/package.py both read it, so a seventh page is added in one place.
SEO_SLUGS = ["istanbul-kiz-yurdu", "istanbul-ogrenci-yurdu",
             "istanbul-kiz-ogrenci-yurdu", "guvenli-kiz-yurdu-istanbul",
             "universitelere-yakin-kiz-yurdu", "kiz-yurdu-fiyatlari"]


def load_origin():
    try:
        cfg = json.load(io.open("site.config.json", encoding="utf-8"))
    except (IOError, ValueError):
        return ""
    return (cfg.get("origin") or "").rstrip("/")


def esc(s):
    return s.replace("&", "&amp;").replace('"', "&quot;")


def structured_data(en, origin):
    """Schema.org LodgingBusiness, built from the same JSON the page renders."""
    c = en["contact"]
    prices = []
    for key in ("f1", "f2", "f3", "f4"):
        digits = re.sub(r"[^\d]", "", en["rooms"][key]["price"])
        if digits:
            prices.append(int(digits))

    data = {
        "@context": "https://schema.org",
        "@type": "LodgingBusiness",
        "name": en["brand"]["name"],
        "description": en["meta"]["description"],
        "address": {
            "@type": "PostalAddress",
            "streetAddress": "Cihangir Mah., Kirazlı Cad. No:18",
            "addressLocality": "Avcılar",
            "addressRegion": "İstanbul",
            "postalCode": "34310",
            "addressCountry": "TR",
        },
        "geo": {
            "@type": "GeoCoordinates",
            "latitude": float(c["mapLat"]),
            "longitude": float(c["mapLng"]),
        },
        "telephone": c["phoneRaw"],
        "email": c["emailRaw"],
        "openingHoursSpecification": [{
            "@type": "OpeningHoursSpecification",
            "dayOfWeek": ["Monday", "Tuesday", "Wednesday", "Thursday",
                          "Friday", "Saturday", "Sunday"],
            "opens": "09:00",
            "closes": "20:00",
        }],
        "priceRange": "₺%s - ₺%s" % (min(prices), max(prices)),
        "currenciesAccepted": "TRY",
        "audience": {"@type": "EducationalAudience", "audienceType": "Students"},
        # Taken from the facilities the page actually lists, never hand-written:
        # an invented "study room" here is a claim the residence has to honour.
        "amenityFeature": [
            {"@type": "LocationFeatureSpecification",
             "name": en["amen"][str(i)]["title"], "value": True}
            for i in range(1, 13) if str(i) in en["amen"]
        ],
    }
    if origin:
        data["url"] = origin + "/"
        data["image"] = origin + "/" + OG_IMAGE
        data["hasMap"] = "https://www.google.com/maps?q=%s,%s" % (c["mapLat"], c["mapLng"])
    return data


def block(page, origin, en, with_jsonld):
    out = [
        '  <meta property="og:locale" content="tr_TR" />',
        '  <meta property="og:locale:alternate" content="en_US" />',
    ]
    if origin:
        url = origin + "/" + PAGES[page]
        out[:0] = ['  <link rel="canonical" href="%s" />' % esc(url)]
        out += [
            '  <meta property="og:url" content="%s" />' % esc(url),
            '  <meta property="og:image" content="%s/%s" />' % (esc(origin), OG_IMAGE),
            '  <meta property="og:image:width" content="1200" />',
            '  <meta property="og:image:height" content="630" />',
        ]
    else:
        out += [
            "  <!-- No canonical or og:image: site.config.json has no origin yet.",
            "       Run  python tools/set-domain.py https://your-domain  to fill them in. -->",
        ]
    if with_jsonld:
        payload = json.dumps(structured_data(en, origin), ensure_ascii=False, indent=2)
        payload = "\n".join("  " + ln for ln in payload.split("\n"))
        out += ['', '  <script type="application/ld+json">', payload, "  </script>"]
    return "\n".join(out)


def stamp(path, body):
    s = io.open(path, encoding="utf-8").read()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(s):
        raise SystemExit("%s: seo markers not found" % path)
    s = pat.sub(lambda m: START + "\n" + body + "\n  " + END, s, count=1)
    io.open(path, "w", encoding="utf-8").write(s)


def main():
    origin = load_origin()
    en = json.load(io.open("i18n/en.json", encoding="utf-8"))

    stamp("index.html", block("index.html", origin, en, True))
    stamp("tools/build-rooms-page.py", block("rooms.html", origin, en, False))
    subprocess.check_call([sys.executable, "tools/build-rooms-page.py"])
    # the landing pages carry their own canonical and og:url
    subprocess.check_call([sys.executable, "tools/build-seo-pages.py"])

    if origin:
        io.open("robots.txt", "w", encoding="utf-8").write(
            "User-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n" % origin)
        # SEO landing pages sit alongside the two core pages
        PAGE_LIST = ([("", "1.0"), ("rooms.html", "0.8")] +
                     [(s + "/", "0.7") for s in SEO_SLUGS])
        urls = "".join(
            '  <url><loc>%s/%s</loc><changefreq>monthly</changefreq>'
            '<priority>%s</priority></url>\n' % (origin, path, pri)
            for path, pri in PAGE_LIST)
        io.open("sitemap.xml", "w", encoding="utf-8").write(
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            "%s</urlset>\n" % urls)
        print("seo: origin=%s | canonical, og:image, robots.txt, sitemap.xml written" % origin)
    else:
        for f in ("robots.txt", "sitemap.xml"):
            if os.path.exists(f):
                os.remove(f)
        print("seo: no origin set -- structured data written, absolute URLs skipped")
        print("     run  python tools/set-domain.py https://your-domain  before launch")


if __name__ == "__main__":
    main()
